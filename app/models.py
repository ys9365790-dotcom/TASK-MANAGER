"""
app/models.py
--------------
Database models for the TaskManager Flask application using Flask-SQLAlchemy.

This module defines three primary entities:
1. User: Represents application users who can create and be assigned tasks.
2. Task: Represents tasks with title, description, status (todo/doing/done),
         priority (low/medium/high), due date, creator, and assignee.
3. ActivityLog: Represents an audit trail of actions performed on tasks or by users.
"""

from datetime import datetime, date
from werkzeug.security import generate_password_hash, check_password_hash
from flask_login import UserMixin
from app import db


class User(db.Model, UserMixin):
    """
    User Model
    ----------
    Stores information about registered users in the system.
    Inherits from Flask-Login's UserMixin to provide authentication properties
    (is_authenticated, is_active, is_anonymous, get_id).

    Attributes:
        id (int): Primary key for the user.
        name (str): Full display name of the user.
        email (str): Unique email address used for identification/login.
        password_hash (str): Securely hashed representation of the user's password.

    Relationships:
        tasks_created: One-to-many relationship linking tasks authored by this user.
        tasks_assigned: One-to-many relationship linking tasks assigned to this user.
        activity_logs: One-to-many relationship linking audit records generated by this user.
    """
    __tablename__ = 'users'

    # Primary key: unique integer identifier for each user
    id = db.Column(db.Integer, primary_key=True)

    # User's full name, cannot be empty
    name = db.Column(db.String(100), nullable=False)

    # Unique email address with an index for fast lookups
    email = db.Column(db.String(120), unique=True, nullable=False, index=True)

    # Hashed password string stored securely (never store raw passwords)
    password_hash = db.Column(db.String(255), nullable=False)

    # Relationship to tasks created by this user
    # foreign_keys specifies which column in 'Task' defines this relation
    tasks_created = db.relationship(
        'Task',
        backref=db.backref('creator', lazy='joined'),
        lazy='dynamic',
        foreign_keys='Task.created_by'
    )

    # Relationship to tasks assigned to this user
    tasks_assigned = db.relationship(
        'Task',
        backref=db.backref('assignee', lazy='joined'),
        lazy='dynamic',
        foreign_keys='Task.assigned_to'
    )

    # Relationship to activity log events triggered by this user
    activity_logs = db.relationship(
        'ActivityLog',
        backref=db.backref('user', lazy='joined'),
        lazy='dynamic',
        foreign_keys='ActivityLog.user_id'
    )

    def set_password(self, password: str) -> None:
        """
        Hash the given plain-text password using Werkzeug's secure hashing algorithm.
        """
        self.password_hash = generate_password_hash(password)

    def check_password(self, password: str) -> bool:
        """
        Verify the given plain-text password against the stored password hash.
        """
        return check_password_hash(self.password_hash, password)

    def to_dict(self) -> dict:
        """
        Serialize user data into a JSON-friendly dictionary (excluding password_hash).
        """
        return {
            'id': self.id,
            'name': self.name,
            'email': self.email
        }

    def __repr__(self) -> str:
        return f"<User id={self.id} name='{self.name}' email='{self.email}'>"


class Task(db.Model):
    """
    Task Model
    ----------
    Stores tasks created within the system.

    Attributes:
        id (int): Primary key for the task.
        title (str): Title or headline of the task.
        description (str): Detailed notes or description of work to be done.
        status (str): Workflow status. Allowed values: 'todo', 'doing', 'done'.
        priority (str): Urgency/importance. Allowed values: 'low', 'medium', 'high'.
        due_date (date): Target completion date (optional).
        assigned_to (int): Foreign key to 'users.id' of the assigned user (optional).
        created_by (int): Foreign key to 'users.id' of the user who authored the task.
        created_at (datetime): Timestamp when the task was initially created.

    Relationships:
        activity_logs: Linked audit records specific to this task.
    """
    __tablename__ = 'tasks'

    # Primary key identifier
    id = db.Column(db.Integer, primary_key=True)

    # Task title: mandatory short summary
    title = db.Column(db.String(200), nullable=False)

    # Optional extended details or instructions
    description = db.Column(db.Text, nullable=True)

    # Status: 'todo', 'doing', or 'done'
    status = db.Column(db.String(20), default='todo', nullable=False)

    # Priority: 'low', 'medium', or 'high'
    priority = db.Column(db.String(20), default='medium', nullable=False)

    # Due date for deadline tracking (stored as date only)
    due_date = db.Column(db.Date, nullable=True)

    # Foreign key referencing the assigned user (nullable if unassigned)
    # ondelete='SET NULL' keeps the task if the user is removed
    assigned_to = db.Column(
        db.Integer,
        db.ForeignKey('users.id', ondelete='SET NULL'),
        nullable=True
    )

    # Foreign key referencing the author user (mandatory)
    created_by = db.Column(
        db.Integer,
        db.ForeignKey('users.id', ondelete='CASCADE'),
        nullable=False
    )

    # Importance for Eisenhower Matrix (Urgent/Important classification)
    important = db.Column(db.Boolean, default=False, nullable=False)

    # Timestamp recorded in UTC when the task is created
    created_at = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)

    # Audit logs connected to this task; preserved in audit history even if task is removed
    activity_logs = db.relationship(
        'ActivityLog',
        backref=db.backref('task', lazy='joined'),
        lazy='dynamic',
        foreign_keys='ActivityLog.task_id'
    )

    @property
    def is_overdue(self) -> bool:
        """
        Returns True if the task has a due date in the past and is not yet 'done'.
        """
        if self.due_date and self.status != 'done':
            return self.due_date < date.today()
        return False

    @property
    def is_due_soon(self) -> bool:
        """
        Returns True if the task is due within 48 hours (today, tomorrow, or day after) and not yet 'done'.
        """
        if self.due_date and self.status != 'done':
            diff_days = (self.due_date - date.today()).days
            return 0 <= diff_days <= 2
        return False

    @property
    def is_urgent(self) -> bool:
        """
        Treat due within 48 hours as urgent (including past due / overdue tasks), provided task is not yet 'done'.
        """
        if self.due_date and self.status != 'done':
            diff_days = (self.due_date - date.today()).days
            return diff_days <= 2
        return False

    @property
    def eisenhower_quadrant(self) -> str:
        """
        Returns the Eisenhower Matrix quadrant:
        - 'q1': Urgent & Important ("Do First")
        - 'q2': Not Urgent & Important ("Schedule / Plan")
        - 'q3': Urgent & Not Important ("Delegate")
        - 'q4': Not Urgent & Not Important ("Don't Do / Eliminate")
        """
        if self.is_urgent and self.important:
            return 'q1'
        elif not self.is_urgent and self.important:
            return 'q2'
        elif self.is_urgent and not self.important:
            return 'q3'
        else:
            return 'q4'

    @property
    def due_urgency(self) -> str:
        """
        Returns 'overdue' (red highlight), 'due-soon' (amber highlight), or 'normal'.
        """
        if self.is_overdue:
            return 'overdue'
        if self.is_due_soon:
            return 'due-soon'
        return 'normal'

    def to_dict(self) -> dict:
        """
        Serialize task data into a JSON-friendly dictionary.
        """
        return {
            'id': self.id,
            'title': self.title,
            'description': self.description,
            'status': self.status,
            'priority': self.priority,
            'important': self.important,
            'is_urgent': self.is_urgent,
            'eisenhower_quadrant': self.eisenhower_quadrant,
            'due_date': self.due_date.isoformat() if self.due_date else None,
            'assigned_to': self.assigned_to,
            'assignee_name': self.assignee.name if self.assignee else 'Unassigned',
            'created_by': self.created_by,
            'creator_name': self.creator.name if self.creator else 'Unknown',
            'created_at': self.created_at.isoformat() if self.created_at else None,
            'is_overdue': self.is_overdue,
            'is_due_soon': self.is_due_soon,
            'due_urgency': self.due_urgency
        }

    def __repr__(self) -> str:
        return f"<Task id={self.id} title='{self.title}' status='{self.status}' priority='{self.priority}' important={self.important}>"


class ActivityLog(db.Model):
    """
    ActivityLog Model
    -----------------
    Audit log tracking significant actions across the application.

    Attributes:
        id (int): Primary key for the log entry.
        task_id (int): Foreign key to 'tasks.id' if the action relates to a specific task.
        user_id (int): Foreign key to 'users.id' of the user who performed the action.
        action (str): Description of the action (e.g. 'Created task', 'Moved to doing').
        timestamp (datetime): Timestamp when the action occurred.
    """
    __tablename__ = 'activity_logs'

    # Primary key identifier
    id = db.Column(db.Integer, primary_key=True)

    # Foreign key referencing the affected task (nullable for system/user-only events)
    task_id = db.Column(
        db.Integer,
        db.ForeignKey('tasks.id', ondelete='SET NULL'),
        nullable=True
    )

    # Foreign key referencing the user who executed the action (nullable for system events)
    user_id = db.Column(
        db.Integer,
        db.ForeignKey('users.id', ondelete='SET NULL'),
        nullable=True
    )

    # Human-readable summary of the action performed
    action = db.Column(db.String(255), nullable=False)

    # Timestamp recorded in UTC when the action occurred
    timestamp = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)

    def to_dict(self) -> dict:
        """
        Serialize activity log data into a JSON-friendly dictionary.
        """
        return {
            'id': self.id,
            'task_id': self.task_id,
            'task_title': self.task.title if self.task else None,
            'user_id': self.user_id,
            'user_name': self.user.name if self.user else 'System',
            'action': self.action,
            'timestamp': self.timestamp.strftime('%Y-%m-%d %H:%M:%S')
        }

    def __repr__(self) -> str:
        return f"<ActivityLog id={self.id} action='{self.action}' at='{self.timestamp}'>"
